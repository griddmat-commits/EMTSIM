"""Generate circuits/grid1000.net: ten 100-node networks joined into a 1013-node example.

    python circuits/make_grid1000.py        (needs Node.js for gui/layout_to_net.js)

Network
-------
* 10 areas, each a copy of the 100-node network in grid100.net (see
  make_grid100.py), drawn in 2 rows of 5:

        A1 -- A2 -- A3 -- A4 -- A5
        |     |     |     |     |
        A6 -- A7 -- A8 -- A9 -- A10

* 13 tie lines (1 ohm + 10 mH in series) join neighbouring areas:
    - horizontal ties from bus B12 of one area to bus B1 of the next,
    - vertical ties from bus B1 of an area in the top row to B1 of the area below.
  Each tie adds one node between its R and L: 10 x 100 + 13 = 1013 nodes.
* The generator angles of area k are shifted by -2 deg x (k - 1), so power flows
  from area to area through the ties.
* Element names start with the area, e.g. A3.R_B1-B2, A7.G5, TIE_A2-A3.R.

Events
------
Only area A1 has the fault and the switching sequence of grid100.net (fault on
feeder 4 at 20 ms, breakers operating between 30 and 90 ms, capacitor bank
energised at 40 ms). In areas A2..A10 the switches never operate, there is no
fault and the capacitor banks stay disconnected. The study therefore shows how
far a disturbance in one area travels through the tie lines.
"""
import os

from make_grid100 import AREA_WIDTH, ROOT, X, Y, Drawing, build_area, doc_comment, netlist_from_drawing, write_netlist

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "grid1000.net")

COLS, ROWS = 5, 2
CX = AREA_WIDTH + 34   # horizontal pitch between areas (room for the tie lines)
RY = 90                # vertical pitch between rows
TIE_R, TIE_L = 1.0, 10e-3

d = Drawing()
origin = {}
for k in range(COLS*ROWS):
    r, c = divmod(k, COLS)
    origin[k] = (c*CX, r*RY)
    build_area(d, *origin[k], prefix="A%d." % (k + 1), events=(k == 0), angle_offset=-2.0*k)


def horizontal_tie(k):
    """From B12 of area k down, right under the feeders, and up onto B1's incoming wire of area k+1."""
    ox, oy = origin[k]
    nx = origin[k + 1][0]
    name = "TIE_A%d-A%d" % (k + 1, k + 2)
    x12 = ox + X[11]
    yt = oy + Y + 46                       # below the deepest feeder
    xr = ox + AREA_WIDTH + 4
    d.wire((x12, oy + Y), (x12, yt), (xr, yt))
    d.add("R", name + ".R", xr, yt, 0, value=TIE_R)
    d.wire((xr + 4, yt), (xr + 7, yt))
    d.add("L", name + ".L", xr + 7, yt, 0, value=TIE_L)
    xin = nx + X[0] - 5                    # on B1's incoming wire, right of its line-charging capacitor
    d.wire((xr + 11, yt), (xin, yt), (xin, oy + Y))


def vertical_tie(k):
    """From B1 of area k straight down onto the return wire (= B1) of the area below."""
    ox, oy = origin[k]
    name = "TIE_A%d-A%d" % (k + 1, k + 1 + COLS)
    x1 = ox + X[0]
    y0 = oy + Y + 50
    d.wire((x1, oy + Y), (x1, y0))
    d.add("R", name + ".R", x1, y0, 90, value=TIE_R)
    d.wire((x1, y0 + 4), (x1, y0 + 6))
    d.add("L", name + ".L", x1, y0 + 6, 90, value=TIE_L)
    d.wire((x1, y0 + 10), (x1, oy + RY + 6))   # the return wire of the area below runs along y = 6


for r in range(ROWS):
    for c in range(COLS - 1):
        horizontal_tie(r*COLS + c)
for c in range(COLS):
    vertical_tie(c)

text, nodes, counts = netlist_from_drawing(d, "1013-node example: 10 joined 100-node networks")
assert nodes == 10*100 + 13, nodes
assert counts["V"] == 150 and counts["SW"] == 60 and counts["F"] == 1, counts
write_netlist(OUT, text, doc_comment(__doc__, [
    "# 1013-node example for EMTSim, generated by circuits/make_grid1000.py.",
    "# Open it in the circuit editor (gui.bat) to see the drawing."]))
print("Wrote %s: %d nodes, %d elements %s" % (os.path.relpath(OUT, ROOT), nodes, sum(counts.values()), counts))
