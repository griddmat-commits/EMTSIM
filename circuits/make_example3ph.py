"""Generate circuits/example3ph.net: a small three-phase example for EMTSim, with a drawing.

    python circuits/make_example3ph.py        (needs Node.js for gui/layout_to_net.js)

Network
-------
            line                       breaker (independent poles)
    G ---- R3 -- L3 ---- bus 3 -------- SW3 ---- bus 4
                          |  |  |                 |   |
                         R3 C3  F3 (a-g)         R3  L3 (motor)

* G: 230 V rms (325 V peak phase-to-ground), 50 Hz, positive sequence,
  0.1 ohm internal resistance (Norton). Phases b and c lag a by 120 and 240 deg.
* Line: 0.5 ohm + 5 mH per phase. Load at bus 3: 20 ohm || 50 uF per phase.
* Motor feeder behind the breaker: 30 ohm || 0.2 H per phase.

Events
------
    40 ms  single-line-to-ground fault, phase a at bus 3 (F3, type a-g)
    70 ms  fault cleared
    80.0 ms  breaker pole a opens
    83.3 ms  breaker pole b opens   (poles part at successive current zeros,
    86.7 ms  breaker pole c opens    about 1/6 cycle apart)

Every part is three-phase in the drawing; the netlist has three single-phase
elements per part (names ending in .a, .b, .c) and drawing node k is netlist
node 3k-2 (a), 3k-1 (b), 3k (c). There is no mutual coupling between phases.
"""
import os

from make_grid100 import ROOT, Drawing, netlist_from_drawing, write_netlist

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "example3ph.net")

d = Drawing(phases=3)
Y = 8
d.add("V3", "G", 2, Y + 4, 270, mag=325.0, angle=0.0, freq=50.0, r=0.1)
d.gnd(2, Y + 4)
d.wire((2, Y), (4, Y))
d.add("R3", "R_line", 4, Y, 0, value=0.5)
d.add("L3", "L_line", 8, Y, 0, value=5e-3)
d.wire((12, Y), (23, Y))                              # bus 3
d.shunt_down("R3", "R_load", 12, Y, value=20.0)
d.shunt_down("C3", "C_load", 16, Y, value=50e-6)
d.add("F3", "F_SLG", 20, Y, 0, kind="a-g", mode="together", t_apply="0.04", t_clear="0.07")
d.add("SW3", "BRK", 23, Y, 0, mode="independent",
      state_a="closed", times_a="0.08", state_b="closed", times_b="0.0833", state_c="closed", times_c="0.0867")
d.wire((27, Y), (30, Y))                              # bus 4
d.shunt_down("R3", "R_motor", 27, Y, value=30.0)
d.shunt_down("L3", "L_motor", 30, Y, value=0.2)

text, nodes, counts = netlist_from_drawing(d, "three-phase example")
assert nodes == 12, nodes          # 4 three-phase nodes x 3 phases
doc = __doc__.split("Network\n-------\n")[1]
write_netlist(OUT, text, ["# Three-phase example for EMTSim, generated by circuits/make_example3ph.py.",
                          "# Open it in the circuit editor (gui.bat) to see the drawing.", "#"] +
              ["# " + l if l else "#" for l in doc.rstrip().splitlines()])
print("Wrote %s: %d netlist nodes (4 three-phase nodes), %d elements %s" %
      (os.path.relpath(OUT, ROOT), nodes, sum(counts.values()), counts))
